import { randomUUID } from 'crypto';
import { Injectable } from '@nestjs/common';
import { AppMessageDto } from './dto/message.dto';
import { MessageSenderRole } from 'src/db/types/db.types';
import { MessageRepository } from './message.repository';
import { GeminiService } from 'src/llm/gemini/gemini.service';
import { PaginatedResult, PaginateOptions } from 'src/shared/dtos/pagination.dto';
import { CreateMessageInput, IMessageService, OnChunkT } from './interfaces/message.service.interface';
import { CreateMessageDto, MessageResponseType } from './dto/create-message.dto';

@Injectable()
export class MessageService implements IMessageService {
  constructor(
    private messageRepository: MessageRepository,
    private geminiService: GeminiService,
  ) {}

  private async streamLLMResponse(llmMessageId: string, data: CreateMessageDto, onChunk: OnChunkT): Promise<string> {
    const chunks = await this.geminiService.askGemini({
      message: data.content,
      model: data.model,
    });

    let fullResponse = '';

    for await (const chunk of chunks) {
      if (!chunk.text) throw new Error('No content generated by LLM');

      onChunk({ id: llmMessageId, type: MessageResponseType.CONTENT, body: chunk.text });
      fullResponse += chunk.text;
    }

    if (!fullResponse.trim()) {
      throw new Error('No content generated by LLM');
    }

    return fullResponse;
  }

  async createMessage({ chatId, data, userId, onChunk }: CreateMessageInput): Promise<void> {
    const llmMessageId = randomUUID();
    const userMessageId = randomUUID();

    try {
      const fullResponse = await this.streamLLMResponse(llmMessageId, data, onChunk);

      await this.messageRepository.createMessage({
        chat_id: chatId,
        user_id: userId,
        id: userMessageId,
        content: data.content,
        role: MessageSenderRole.USER,
        parent_message_id: data.parent_message_id,
      });
      await this.messageRepository.createMessage({
        chat_id: chatId,
        id: llmMessageId,
        content: fullResponse,
        llm_model: data.model,
        parent_message_id: userMessageId,
        role: MessageSenderRole.MODEL,
      });

      onChunk({ type: MessageResponseType.COMPLETE, id: llmMessageId });
    } catch (error) {
      console.error('Error in streaming:', error);
      const errorMessage = error instanceof Error ? error.message : 'Unknown error occurred';
      onChunk({ type: MessageResponseType.ERROR, id: llmMessageId, error: errorMessage });
      throw error;
    }
  }

  getChatMessages(chatId: string, pagination: PaginateOptions): Promise<PaginatedResult<AppMessageDto>> {
    return this.messageRepository.getChatMessages(chatId, pagination);
  }
}
