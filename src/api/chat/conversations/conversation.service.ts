import { Injectable } from '@nestjs/common';
import { GeminiService } from 'src/llm/gemini/gemini.service';
import { MessageRepository } from '../messages/message.repository';
import { BranchContextRepository } from '../branch-contexts/branch-context.repository';
import { MessageSenderRole } from 'src/db/types/db.types';
import { ConversationResponseType } from './dto/create-conversation.dto';
import {
  AskAiInput,
  GenerateAIPromptInput,
  GenerateChatTitleOutput,
  GetAIContextOutput,
  SaveConversationDataInput,
  StreamLLMResponseInput,
} from './types/conversation.service.types';
import { ChatRepository } from '../chats/chat.repository';
import { Transaction } from 'src/db/transactions/transaction.decorator';
import { ConversationRepository } from './conversation.repository';
import { titlePrompt } from 'src/llm/prompts/title';
import { MessageReplyRepository } from '../messages/message-reply.repository';

@Injectable()
export class ConversationService {
  constructor(
    private geminiService: GeminiService,
    private chatRepository: ChatRepository,
    private messageRepository: MessageRepository,
    private messageReplyRepository: MessageReplyRepository,
    private conversationRepository: ConversationRepository,
    private branchContextRepository: BranchContextRepository,
  ) {}

  private async generateAIPrompt({ userInput, chatId, replyTo }: GenerateAIPromptInput): Promise<GetAIContextOutput[] | string> {
    const fullContext = await this.conversationRepository.getFullContextForCurrentConversation(chatId);

    const result = fullContext.map(message => ({
      role: message.role,
      parts: [{ text: message.content }],
    }));

    return [
      ...result,
      {
        role: MessageSenderRole.USER,
        parts: [
          { text: 'Give short answer' },
          { text: userInput },
          ...(replyTo ? [{ text: `The user is referring to this in particular:\n${replyTo}` }] : []),
        ],
      },
    ];
  }

  private async streamLLMResponse({ llmMessageId, contents, model, onChunk }: StreamLLMResponseInput): Promise<string> {
    const chunks = await this.geminiService.askGeminiWithStream({
      contents,
      model: model,
      config: { temperature: 0.7 },
    });

    let fullResponse = '';

    for await (const chunk of chunks) {
      if (!chunk.text) throw new Error('No content generated by LLM');

      onChunk({ type: ConversationResponseType.CONTENT, id: llmMessageId, body: chunk.text });
      fullResponse += chunk.text;
    }

    if (!fullResponse.trim()) {
      throw new Error('No content generated by LLM');
    }

    return fullResponse;
  }

  private async generateChatTitle({ model, userInput }: GenerateChatTitleOutput): Promise<string> {
    const geminiResponse = await this.geminiService.askGemini({
      model: model,
      contents: `${titlePrompt} \n User question: ${userInput}`,
      config: {
        temperature: 0.3,
        maxOutputTokens: 50,
      },
    });

    return geminiResponse.text || 'New conversation';
  }

  @Transaction()
  private async saveConversationData({ data, fullLlmResponse, llmMessageId, userId, chatTitle }: SaveConversationDataInput) {
    // If there is chatTitle that means the first message in the chat was sent
    if (chatTitle) {
      await this.chatRepository.updateChat(data.chat_id, { name: chatTitle });
    }

    await this.messageRepository.createMessage({
      chat_id: data.chat_id,
      user_id: userId,
      id: data.message_id,
      content: data.content,
      role: MessageSenderRole.USER,
      // Date is passed because messages are in transaction and they are flushed at the same time. Ruins messages order
      created_at: new Date().toISOString(),
      parent_message_id: data.branch_context?.parent_message_id,
    });

    await this.messageRepository.createMessage({
      id: llmMessageId,
      chat_id: data.chat_id,
      llm_model: data.model,
      content: fullLlmResponse,
      role: MessageSenderRole.MODEL,
      // Date is passed because messages are in transaction and they are flushed at the same time. Ruins messages order
      created_at: new Date().toISOString(),
    });

    if (data.reply_to) {
      await this.messageReplyRepository.createMessageReply({
        message_id: data.message_id,
        message_id_replied_to: data.reply_to.id,
        reply_content: data.reply_to.content,
      });
    }

    if (data.branch_context) {
      await this.branchContextRepository.updateBranchContextByChildChatId(data.chat_id, { child_message_id: data.message_id });
    }
  }

  async askAi({ data, userId, onChunk }: AskAiInput): Promise<void> {
    let chatTitle: string | undefined;

    try {
      const chatHasMessages = await this.messageRepository.checkIfChatHasMessages(data.chat_id);

      const promptToAI = await this.generateAIPrompt({
        chatId: data.chat_id,
        userInput: data.content,
        replyTo: data.reply_to?.content,
      });

      const fullLlmResponse = await this.streamLLMResponse({
        onChunk,
        model: data.model,
        contents: promptToAI,
        llmMessageId: data.future_llm_message_id,
      });

      if (!chatHasMessages) {
        chatTitle = await this.generateChatTitle({
          model: data.model,
          userInput: data.content,
        });

        onChunk({ type: ConversationResponseType.TITLE, chat_id: data.chat_id, title: chatTitle });
      }

      await this.saveConversationData({ data, fullLlmResponse, llmMessageId: data.future_llm_message_id, userId, chatTitle });

      onChunk({ type: ConversationResponseType.COMPLETE, id: data.future_llm_message_id });
    } catch (error) {
      console.error('Error in streaming:', error);
      const errorMessage = error instanceof Error ? error.message : 'Unknown error occurred';
      onChunk({ type: ConversationResponseType.ERROR, id: data.future_llm_message_id, error: errorMessage });
      throw new Error(errorMessage);
    }
  }
}
