import { Injectable } from '@nestjs/common';
import { randomUUID } from 'crypto';
import { GeminiService } from 'src/llm/gemini/gemini.service';
import { MessageRepository } from '../messages/message.repository';
import { ThreadContextRepository } from '../thread-contexts/thread-context.repository';
import { MessageSenderRole } from 'src/db/types/db.types';
import { ConversationResponseType } from './dto/create-conversation.dto';
import {
  AskAiInput,
  GenerateChatTitleOutput,
  GetAIContextOutput,
  SaveConversationDataInput,
  StreamLLMResponseInput,
} from './types/conversation.service.types';
import { generateRandomPastelHexColor } from 'src/shared/utils/generate-random-hex';
import { ChatRepository } from '../chats/chat.repository';
import { Transaction } from 'src/db/transactions/transaction.decorator';
import { ConversationRepository } from './conversation.repository';
import { titlePrompt } from 'src/llm/prompts/title';

@Injectable()
export class ConversationService {
  constructor(
    private geminiService: GeminiService,
    private chatRepository: ChatRepository,
    private messageRepository: MessageRepository,
    private conversationRepository: ConversationRepository,
    private threadContextRepository: ThreadContextRepository,
  ) {}

  private async generateAIPrompt(userInput: string, chatId?: string): Promise<GetAIContextOutput[] | string> {
    // If there is not chatId it means the root chat was created
    if (!chatId) {
      return userInput;
    }

    const contextMessages = await this.conversationRepository.getMessagesForAiContext(chatId);

    const result = contextMessages.map(message => ({
      role: message.role,
      parts: [{ text: message.content }],
    }));

    return [...result, { role: MessageSenderRole.USER, parts: [{ text: userInput }] }];
  }

  private async streamLLMResponse({ llmMessageId, contents, model, onChunk }: StreamLLMResponseInput): Promise<string> {
    const chunks = await this.geminiService.askGeminiWithStream({
      contents,
      model: model,
    });

    let fullResponse = '';

    for await (const chunk of chunks) {
      if (!chunk.text) throw new Error('No content generated by LLM');

      onChunk({ id: llmMessageId, type: ConversationResponseType.CONTENT, body: chunk.text });
      fullResponse += chunk.text;
    }

    if (!fullResponse.trim()) {
      throw new Error('No content generated by LLM');
    }

    return fullResponse;
  }

  private async generateChatTitle({ model, userInput }: GenerateChatTitleOutput): Promise<string> {
    const geminiResponse = await this.geminiService.askGemini({
      model: model,
      contents: `${titlePrompt} \n User question: ${userInput}`,
      config: {
        temperature: 0.3,
        maxOutputTokens: 50,
      },
    });

    return geminiResponse.text || 'New conversation';
  }

  @Transaction()
  private async saveConversationData({ data, fullLlmResponse, llmMessageId, userId }: SaveConversationDataInput) {
    const chat = await this.chatRepository.getChatById(data.chat_id);

    // A conversation was initialized to a non existing chat/thread
    if (!chat) {
      let threadLevel = 0;
      let rootChatId: string | undefined;
      let contextPath: string[] = [data.chat_id];

      // A conversation was initialized in a thread
      if (data.thread_context) {
        const parentChat = await this.chatRepository.getChatById(data.thread_context.parent_chat_id);

        if (parentChat) {
          threadLevel = parentChat.thread_level + 1;
          // parentChat may not have root_chat_id as parent might be the root itself
          rootChatId = parentChat.root_chat_id || data.thread_context.parent_chat_id;
          // parentChat.path = ['root_id', 'parent_chat_id']
          contextPath = [...parentChat.path, data.chat_id];
        }
      }

      await this.chatRepository.createChat({
        user_id: userId,
        id: data.chat_id,
        path: contextPath,
        root_chat_id: rootChatId,
        thread_level: threadLevel,
        parent_chat_id: data.thread_context?.parent_chat_id,
      });
    }

    await this.messageRepository.createMessage({
      chat_id: data.chat_id,
      user_id: userId,
      id: data.message_id,
      content: data.content,
      role: MessageSenderRole.USER,
      // Date is passed because messages are in transaction and they are flushed at the same time. Ruins messages order
      created_at: new Date().toISOString(),
      parent_message_id: data.thread_context?.parent_message_id,
    });

    await this.messageRepository.createMessage({
      id: llmMessageId,
      chat_id: data.chat_id,
      llm_model: data.model,
      content: fullLlmResponse,
      role: MessageSenderRole.MODEL,
      // Date is passed because messages are in transaction and they are flushed at the same time. Ruins messages order
      created_at: new Date().toISOString(),
    });

    if (data.thread_context) {
      await this.threadContextRepository.createThreadContext({
        child_chat_id: data.chat_id,
        child_message_id: data.message_id,
        context_type: data.thread_context?.context_type,
        end_position: data.thread_context?.end_position,
        connection_color: generateRandomPastelHexColor(),
        selected_text: data.thread_context?.selected_text,
        parent_chat_id: data.thread_context?.parent_chat_id,
        start_position: data.thread_context?.start_position,
        connection_type: data.thread_context?.connection_type,
        parent_message_id: data.thread_context?.parent_message_id,
      });
    }
  }

  // The function handles messages in main chats and threads
  async askAi({ data, userId, onChunk }: AskAiInput): Promise<void> {
    const llmMessageId = randomUUID();
    let chatTitle: string | undefined;

    try {
      // If user creates a thread we need to get parent context as child chat doesn't exist yet
      const chatInfo = await this.chatRepository.getChatById(data.thread_context?.parent_chat_id || data.chat_id);

      const promptToAI = await this.generateAIPrompt(data.content, chatInfo?.id);

      const fullLlmResponse = await this.streamLLMResponse({
        onChunk,
        llmMessageId,
        model: data.model,
        contents: promptToAI,
      });

      if (!chatInfo) {
        chatTitle = await this.generateChatTitle({
          model: data.model,
          userInput: data.content,
        });

        onChunk({ chat_id: data.chat_id, type: ConversationResponseType.TITLE, title: chatTitle });
      }

      await this.saveConversationData({ data, fullLlmResponse, llmMessageId, userId, chatTitle });

      onChunk({ id: llmMessageId, type: ConversationResponseType.COMPLETE });
    } catch (error) {
      console.error('Error in streaming:', error);
      const errorMessage = error instanceof Error ? error.message : 'Unknown error occurred';
      onChunk({ id: llmMessageId, type: ConversationResponseType.ERROR, error: errorMessage });
      throw new Error(errorMessage);
    }
  }
}
